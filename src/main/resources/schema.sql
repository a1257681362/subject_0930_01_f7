    CONSTRAINT uk_cc_inspector_region UNIQUE (username, region_code)
);

-- 抽检任务（一个运输批次可多次抽检；任务按监管区域隔离）
CREATE TABLE IF NOT EXISTS t_cc_inspection_task (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no            VARCHAR(32)  NOT NULL,          -- 抽检任务号，序列生成，稳定唯一
    batch_id           BIGINT       NOT NULL,          -- 被抽检的运输批次（追溯锚点）
    supervise_region   VARCHAR(32)  NOT NULL,          -- 监管区域（查询隔离依据）
    task_name          VARCHAR(128),                   -- 任务名称/抽检事由
    sampling_location  VARCHAR(255),                   -- 任务默认采样位置（样本可逐条细化）
    sampler_name       VARCHAR(64),                    -- 任务默认采样人
    -- PLANNED 已立项封存中 / CONCLUDED 已出抽检结论（任务与样本均不提供删除路径）
    status             VARCHAR(16)  NOT NULL DEFAULT 'PLANNED',
    -- 抽检结论（回写批次独立列；结论只追加一次）：PASS 合格 / FAIL 不合格
    result             VARCHAR(16),
    conclusion         VARCHAR(1000),
    conclude_by        BIGINT,
    conclude_name      VARCHAR(64),
    conclude_time      TIMESTAMP,
    remark             VARCHAR(255),
    create_by          BIGINT,
    create_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by          BIGINT,
    update_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_inspection_no UNIQUE (task_no)
);
CREATE INDEX IF NOT EXISTS idx_cc_inspection_batch ON t_cc_inspection_task (batch_id, id);
CREATE INDEX IF NOT EXISTS idx_cc_inspection_region ON t_cc_inspection_task (supervise_region, id);

-- 抽检样本（封存码库内唯一不复用；封存后只沿状态前进，不可更新/删除）
CREATE TABLE IF NOT EXISTS t_cc_inspection_sample (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id            BIGINT       NOT NULL,
    batch_id           BIGINT       NOT NULL,          -- 冗余批次，便于按批次追溯
    sample_seq         INT          NOT NULL,          -- 任务内样本序号，从 1 递增
    seal_code          VARCHAR(64)  NOT NULL,          -- 唯一封存码，序列生成，库内唯一不复用
    quantity           INT          NOT NULL,          -- 抽样数量（必须 > 0）
    unit               VARCHAR(16)  NOT NULL DEFAULT '盒',
    sample_location    VARCHAR(255) NOT NULL,          -- 采样位置
    sampler_name       VARCHAR(64)  NOT NULL,          -- 采样人
    -- 封存照片（封存当刻写入，之后不可更换/删除）
    seal_photo_name    VARCHAR(255) NOT NULL,
    seal_photo_url     VARCHAR(500) NOT NULL,
    seal_photo_sha256  VARCHAR(64),                    -- 照片内容摘要（有内容时落库）
    -- SEALED 已封存 / TRANSFERRED 已完成至少一次双人转移（当前持有方见 custodian_*）
    status             VARCHAR(16)  NOT NULL DEFAULT 'SEALED',
    custodian_name     VARCHAR(64)  NOT NULL,          -- 当前持有（保管）人
    custodian_org      VARCHAR(128),                   -- 当前持有责任主体
    transfer_count     INT          NOT NULL DEFAULT 0,-- 已完成双人转移次数
    seal_time          TIMESTAMP    NOT NULL,          -- 封存时间
    create_by          BIGINT,
    create_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by          BIGINT,
    update_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_seal_code UNIQUE (seal_code),
    CONSTRAINT ck_cc_sample_qty CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS idx_cc_sample_task ON t_cc_inspection_sample (task_id, sample_seq);
CREATE INDEX IF NOT EXISTS idx_cc_sample_batch ON t_cc_inspection_sample (batch_id, id);

-- 样本转移单（双人确认：移交人发起停留 PENDING，接收人第二账号确认后 CONFIRMED；只追加）
CREATE TABLE IF NOT EXISTS t_cc_sample_transfer (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id          BIGINT       NOT NULL,
    task_id            BIGINT       NOT NULL,
    batch_id           BIGINT       NOT NULL,
    transfer_seq       INT          NOT NULL,          -- 同一样本第几次转移，从 1 递增
    handover_location  VARCHAR(255) NOT NULL,          -- 移交地点
    transfer_note      VARCHAR(500),
    -- 移交方（发起即确认，不可再改）
    from_custodian_name VARCHAR(64) NOT NULL,
    from_custodian_org  VARCHAR(128),
    sender_name        VARCHAR(64)  NOT NULL,          -- 移交人账号（双人校验依据）
    sender_display     VARCHAR(64)  NOT NULL,          -- 移交人姓名快照
    sender_confirm_time TIMESTAMP   NOT NULL,
    -- 接收方（第二人确认后落位；PENDING 期间为拟接收方）
    to_custodian_name  VARCHAR(64)  NOT NULL,          -- 拟接收/实际接收人姓名
    to_custodian_org   VARCHAR(128),
    receiver_name      VARCHAR(64),                    -- 接收人账号（必须与移交人不同）
    receiver_display   VARCHAR(64),
    receiver_confirm_time TIMESTAMP,
    -- PENDING 待接收人确认（只完成一半）/ CONFIRMED 双人确认完成
    status             VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    create_by          BIGINT,
    create_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by          BIGINT,
    update_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cc_transfer_sample ON t_cc_sample_transfer (sample_id, transfer_seq);
CREATE INDEX IF NOT EXISTS idx_cc_transfer_status ON t_cc_sample_transfer (status, id);

