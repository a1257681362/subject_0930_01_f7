-- 设计要点：
-- 1. 一车货到中转仓后可拆成多个交接单：t_cc_handover_order 每单记录箱数、交接温度、
--    接收人与交接时刻；同批次全部交接单箱数合计必须等于到仓总箱数（箱数平衡），
--    不多不少，否则禁止建单/提交。
-- 2. 封签逐条核验：t_cc_handover_seal 记录每个封签号及其核验状态；封签号在“同一运输批次
--    范围内（含历史交接单）”唯一，封签重复拒绝并指明与哪一单冲突。每个封签可追加核验说明
--    与核验时间/核验人（只追加确认事实，不提供改写或删除路径）。
-- 3. 提交即责任转移：单内每个封签都已核验后才允许提交；提交后置 SUBMITTED，冻结箱数/封签/
--    温度/接收人，责任主体由原承运批次转移到该单接收人（responsible_org/owner 快照到单与批次）。
-- 4. 未完成核验的箱子不能继续派送：批次全部到仓箱数必须都已分到交接单且所在单均 SUBMITTED
--    （全部封签已核验）才允许签收闭环/继续派送。
-- 5. 原运输批次仍可追溯全部节点：交接单/封签/核验/责任转移全部写 t_cc_op_log 并带 batch_id，
--    批次台账聚合全部交接单；交接单只追加不改写（作废仅置 VOID 状态，不删封签/核验/日志）。
-- 6. 权限收紧冻结推进：t_cc_permission_setting 以“权限键 + 开/关”表达可被收紧的业务权限；
--    冷链药品运输权限（COLD_CHAIN_HANDOVER）一旦收紧，建单/核验/提交/签收一律停止推进，
