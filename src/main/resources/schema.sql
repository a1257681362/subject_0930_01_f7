-- ============================================================================
-- 按药品类别的温控预警模板（V5 / cold-chain-5）
-- 设计要点：
-- 1. 药品挂到“类别树”（t_cc_drug_category，parent_id 自引用，根类别 parent_id 为空）。
--    每个类别可维护一份温控预警模板（t_cc_alert_template，一类一行）；模板按“温区行”
--    （t_cc_alert_template_zone）逐温区给阈值，温区行只追加，模板修改=停旧行+新生效行。
-- 2. 继承与覆盖：类别模板未显式配置某个温区时，沿 parent_id 向上继承最近一级已配置的
--    阈值；类别在指定温区显式给值即覆盖上级阈值。修改模板只影响此后新建的批次。
-- 3. 创建时快照：派车生成批次时按药品类别把“解析后的生效模板（含继承来源标记）”逐行
--    固化到 t_cc_batch_alert_zone_snap；此后类别树/模板如何变更，本批次的越限判定、
--    连续超限计时、预警追溯一律以创建时快照为准（与档案快照、路线分段快照同一口径）。
-- 4. 按采样点计算连续超限：t_cc_alert_streak 以“批次×探头（采样点）”为粒度保存连续超限
--    计时状态。采样点回正常时，若正常时长不超过模板“抖动合并时长”，视为短暂抖动、连续
--    超限合并不断开（streak 保持）；超过合并窗才真正断开。连续超限达到模板容忍时长
--    （持续超过容忍分钟）即产生一条预警。
-- 5. 预警只追加、幂等：t_cc_temp_alert 记录预警（含采样点、温区、模板快照参数），
--    一次连续超限只产一条，uk_cc_alert_open 在数据库层兜底定时任务重启/并发重复扫描；
--    闭环只追加处理字段，预警绝不因模板后续修改而消失或被改写。
-- ============================================================================

