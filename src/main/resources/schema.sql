-- 药品运输抽检与运输审批（V7 / cold-chain-7）
-- 设计要点：
-- 1. 监管人员按运输批次发起抽检任务（t_cc_inspection_task），任务归属“监管区域”；
--    监管人员可管辖的区域在 t_cc_inspector_region 授权，查询/详情/封存/转移/结论
--    一律按授权区域隔离，跨区域访问直接拒绝（'*' 为全域，仅管理员）。
-- 2. 一次抽检按批次抽取多个样本（t_cc_inspection_sample）：封存码由数据库序列生成、
--    库内唯一且永不复用，封存当刻一并记录采样人、采样位置、数量与封存照片
--    （名称/地址），封存后样本只沿状态前进（SEALED -> TRANSFERRED），
--    系统不提供任何更新/删除样本或照片的路径。
-- 3. 样本转移（t_cc_sample_transfer）必须双人确认：移交人发起即记录移交人确认，
--    单据停留 PENDING；接收人（必须是不同于移交人的第二个登录账号）确认后才 CONFIRMED，
--    样本当前持有方随确认转移。每次转移追加一行，形成完整转移链，只追加不改写。
-- 4. 抽检结论（合格/不合格 + 说明）回写 t_cc_transport_batch 的独立抽检列，
--    绝不修改批次状态、温度、异常、交接等任何原始运输记录；结论只追加一次。
-- 5. 冷链运输审批（t_cc_inspection_approval）两步走：申请 -> 待审批（PENDING）->
--    同意/驳回。只完成一半（已申请未审批）时审批停留待处理，已申请审批的批次
--    在 PENDING/REJECTED 下不得发运；审批进行期间抽检任务与样本封存照常可办、可追溯。
-- 6. 抽检/样本/转移/审批全部关键动作写 t_cc_op_log 并带 batch_id，原批次台账可串联
--    抽检任务、样本封存、双人转移链与审批节点。
-- ============================================================================

